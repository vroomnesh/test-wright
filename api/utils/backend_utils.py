# Centralized environment variable loading and validation
def load_env():
    """Load environment variables from .env file"""
    # Load .env file from the project root directory
    # Go up two levels from api/utils/backend_utils.py to reach project root
    env_path = os.path.join(os.path.dirname(os.path.dirname(os.path.dirname(__file__))), '.env')
    load_dotenv(env_path)
    return {
        # OpenAI API configuration. Model ids are OpenAI model names, not Azure deployments.
        "OPENAI_API_KEY": os.getenv("OPENAI_API_KEY"),
        "CHAT_MODEL": os.getenv("OPENAI_CHAT_MODEL") or "gpt-4o",
        "EMB_MODEL": os.getenv("OPENAI_EMBEDDING_MODEL") or "text-embedding-ada-002",

        # Weaviate Configuration
        "WEAVIATE_URL":               os.getenv("WEAVIATE_URL"),
        "WEAVIATE_API_KEY":           os.getenv("WEAVIATE_API_KEY"),
    }


