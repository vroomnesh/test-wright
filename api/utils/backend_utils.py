# Functions for converting CSV to Excel with proper formatting and styling
def clean_llm_csv(csv_text: str) -> str:
    """Drop markdown fences and any commentary around an LLM CSV table."""
    if not csv_text:
        return ""

    lines = []
    started = False
    for line in csv_text.strip().splitlines():
        stripped = line.strip()
        if stripped.startswith("```"):
            if started:
                break
            continue
        if not started:
            if "Test Case ID" not in stripped and "Testcase no" not in stripped:
                continue
            started = True
        lines.append(line)
    return "\n".join(lines).strip()


def parse_test_case_csv(csv_text: str) -> list:
    """Parse LLM CSV into row dicts, ignoring fence lines and leftover columns."""
    import csv

    reader = csv.DictReader(io.StringIO(clean_llm_csv(csv_text)))
    rows = []
    for row in reader:
        item = {}
        for key, value in row.items():
            if key is None:
                continue
            header = str(key).strip().strip('"')
            if not header or header.lower() in {"null", "```csv", "```"}:
                continue
            item[header] = "" if value is None else value

        test_case_id = (item.get("Test Case ID") or "").strip()
        if not test_case_id or test_case_id.lower() in {"test case id", "```csv", "```"}:
            continue
        rows.append(item)
    return rows


def _rows_to_csv(rows: list) -> str:
    """Write parsed test-case rows back to CSV."""
    import csv

    if not rows:
        return ""
    buffer = io.StringIO()
    fieldnames = list(rows[0].keys())
    writer = csv.DictWriter(buffer, fieldnames=fieldnames, quoting=csv.QUOTE_MINIMAL, lineterminator="\n")
    writer.writeheader()
    writer.writerows(rows)
    return buffer.getvalue().strip()


def chat_test_case_csv(oa, messages) -> str:
    """
    Generate the full CSV. One model reply is limited to 16384 tokens, which
    often ends near 20 long rows, so keep asking for the remaining rows until
    the model finishes or six replies have been collected.
    """
    env = load_env()
    chat_model = env["CHAT_MODEL"]
    collected = []
    seen = set()
    header_line = ""

    for _ in range(6):
        resp = oa.chat.completions.create(
            model=chat_model,
            messages=messages,
            temperature=0.2,
            max_tokens=16384,
        )
        text = (resp.choices[0].message.content or "").strip()
        chunk = text
        if header_line and "Test Case ID" not in text and "Testcase no" not in text:
            chunk = header_line + "\n" + text
        rows = parse_test_case_csv(chunk)
        if rows and not header_line:
            header_line = ",".join(f'"{key}"' for key in rows[0].keys())
        truncated = getattr(resp.choices[0], "finish_reason", None) == "length"
        if truncated and len(rows) > 1:
            rows = rows[:-1]
        for row in rows:
            case_id = (row.get("Test Case ID") or row.get("Testcase no") or "").strip()
            if not case_id or case_id in seen:
                continue
            seen.add(case_id)
            collected.append(row)
        if not truncated:
            break
        last_id = ""
        if collected:
            last_id = (collected[-1].get("Test Case ID") or collected[-1].get("Testcase no") or "").strip()
        messages = list(messages) + [
            {"role": "assistant", "content": text},
            {
                "role": "user",
                "content": (
                    f"The CSV was cut off after {last_id or 'the header'}. "
                    "Continue with the remaining test cases only. Do not repeat the header or any earlier case. "
                    "Fewer than 20 and more than 20 are both valid. Output raw CSV rows until every remaining item is covered."
                ),
            },
        ]

    return _rows_to_csv(collected)


def csv_to_excel_bytes(csv_text: str) -> bytes:
    """
    Fast CSV to Excel conversion with minimal formatting.
    """
    rows = parse_test_case_csv(csv_text)
    if rows:
        df = pd.DataFrame(rows)
    else:
        csv_text = clean_llm_csv(csv_text)
        # Use faster CSV parsing with minimal error handling
        try:
            df = pd.read_csv(
                io.StringIO(csv_text),
                sep=",",
                engine="c",  # Faster C engine
                quotechar='"',
                on_bad_lines="skip"
            )
        except (TypeError, Exception):
            # Fallback to python engine if C engine fails
            df = pd.read_csv(
                io.StringIO(csv_text),
                sep=",",
                engine="python",
                quotechar='"',
                on_bad_lines="skip"
            )

    # Remove all quotes from the data
    df = df.replace('"', '', regex=True)

    # Enhanced newline conversion for proper Excel line breaks
    # Handle various newline formats that might come from the LLM in a specific order
    # First handle escaped newlines, then literal \n text
    df = df.replace(r'\\n', '\n', regex=True)    # Handle escaped \\n first
    df = df.replace('\\n', '\n', regex=False)    # Handle string \\n (non-regex to avoid conflicts)

    # Special handling for columns that should have proper line breaks
    for col in df.columns:
        if col in ['Steps to be Executed', 'Test Input Data', 'Test Step Description', 'Expected Result']:
            # Ensure proper newline formatting for these columns
            df[col] = df[col].astype(str).apply(
                lambda x: x.replace('\\n', '\n').replace('\r\n', '\n').replace('\r', '\n')
                if isinstance(x, str) else x
            )

    # Use openpyxl directly with enhanced formatting for detailed test steps
    buffer = io.BytesIO()
    with pd.ExcelWriter(buffer, engine="openpyxl") as writer:
        sheet = "Test_Cases"
        df.to_excel(writer, index=False, sheet_name=sheet)

        # Get the worksheet for formatting
        worksheet = writer.sheets[sheet]

        # Enhanced column sizing for detailed test steps
