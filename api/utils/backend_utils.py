def etl_csv_to_excel_bytes(csv_text: str) -> bytes:
    """
    ETL-specific CSV to Excel conversion with cell merging for Testcase no, Rule_Name, Test description.
    Keeps Test step, Expected result, Test Scripts formatting exactly as-is.
    """
    cleaned = clean_llm_csv(csv_text)
    if cleaned:
        csv_text = cleaned
    import csv
    reader = csv.DictReader(io.StringIO(csv_text))
    rows = []
    for row in reader:
        item = {}
        for key, value in row.items():
            if key is None:
                continue
            header = str(key).strip().strip('"')
            if not header:
                continue
            item[header] = "" if value is None else value
        if any(str(value).strip() for value in item.values()):
            rows.append(item)
    df = pd.DataFrame(rows)

    for col in df.columns:
        df[col] = df[col].astype(str).str.replace("\\n", "\n", regex=False)

    # Use openpyxl directly with merged cell formatting
    buffer = io.BytesIO()
    with pd.ExcelWriter(buffer, engine="openpyxl") as writer:
        sheet = "Test_Cases"
        df.to_excel(writer, index=False, sheet_name=sheet)

        # Get the worksheet for formatting
        worksheet = writer.sheets[sheet]

        # Auto-size columns
        for col_idx, col in enumerate(df.columns):
            max_len = min(max(df[col].astype(str).map(len).max(), len(col)) + 2, 50)  # Cap at 50 chars
            worksheet.column_dimensions[worksheet.cell(1, col_idx + 1).column_letter].width = max_len

        # ETL-specific: Create merged cells for first 5 columns (Testcase no, Table name, Field name, Rule_Name, Test description)
        # Only merge if we have the expected ETL column structure with 8 columns
        expected_columns = ['Testcase no', 'Table name', 'Field name', 'Rule_Name', 'Test description', 'Test step', 'Expected result', 'Test Scripts']
        if len(df.columns) >= 8 and list(df.columns) == expected_columns:
            current_row = 2  # Start from row 2 (after header)

            while current_row <= len(df) + 1:  # +1 because Excel is 1-indexed and we have header
                # Find the start of a test case group (non-empty Testcase no)
                if current_row > len(df) + 1:
                    break

                testcase_value = worksheet.cell(current_row, 1).value  # Column A (Testcase no)
                if testcase_value and str(testcase_value).strip():  # Non-empty testcase
                    # Find the end of this test case group (next non-empty testcase or end of data)
                    group_start = current_row
                    group_end = current_row

                    # Look ahead to find where this group ends
                    next_row = current_row + 1
                    while next_row <= len(df) + 1:
                        next_testcase = worksheet.cell(next_row, 1).value if next_row <= len(df) + 1 else None
                        if next_testcase and str(next_testcase).strip():  # Found next test case
                            break
                        group_end = next_row
                        next_row += 1

                    # Merge cells for this group if it spans multiple rows
                    if group_end > group_start:
                        # Merge first 5 columns (A through E)
                        # A: Testcase no, B: Table name, C: Field name, D: Rule_Name, E: Test description
                        worksheet.merge_cells(f'A{group_start}:A{group_end}')  # Testcase no
                        worksheet.merge_cells(f'B{group_start}:B{group_end}')  # Table name
                        worksheet.merge_cells(f'C{group_start}:C{group_end}')  # Field name
                        worksheet.merge_cells(f'D{group_start}:D{group_end}')  # Rule_Name
                        worksheet.merge_cells(f'E{group_start}:E{group_end}')  # Test description

                        # Center align the merged cells vertically
                        from openpyxl.styles import Alignment
                        for col in ['A', 'B', 'C', 'D', 'E']:
                            cell = worksheet[f'{col}{group_start}']
                            cell.alignment = Alignment(vertical='center', wrap_text=True)

                    current_row = group_end + 1
                else:
                    current_row += 1

    return buffer.getvalue()

