def _sql_name(name: str) -> str:
    """Quote a table or column name for Spark SQL."""
    cleaned = (name or "").strip().replace("`", "")
    return f"`{cleaned}`"


def _sql_value_expr(field: str) -> str:
    """Return a Spark SQL expression, leaving calculations unquoted."""
    field = (field or "").strip()
    if re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", field):
        return _sql_name(field)
    return f"({field})"


def _script_kind(testcase_no: str) -> str:
    """Match the suffix used on generated ETL test case ids."""
    name = testcase_no or ""
    for suffix, kind in (
        ("_AuditColumns", "audit"),
        ("_NullCheck", "null"),
        ("_Null_Check", "null"),
        ("_Duplicate", "duplicate"),
        ("_Duplicate_Check", "duplicate"),
        ("_Direct_Validation", "data"),
        ("_Count", "count"),
        ("_Data", "data"),
    ):
        if name.endswith(suffix):
            return kind
    return "data"


def generate_pyspark_test_script(test_case: dict, test_step: str, expected_result: str, step_index: int) -> str:
    """
    Generate a PySpark assertion for any mapping row.

    Count and data checks have three steps, so only the last step asserts.
    Null, duplicate, and audit checks have one step, so that step asserts.
    Value checks compare column values, so a renamed source column still matches its target.
    """
    sources = test_case.get('sources', [])
    targets = test_case.get('targets', [])

    source_table = 'source_table'
    target_table = 'target_table'
    source_field = 'source_field'
    target_field = 'target_field'

    if sources:
        source_table = (sources[0].get('coll') or source_table).strip()
        source_field = (sources[0].get('cols_attrs') or source_field).strip()
    if targets:
        target_table = (targets[0].get('coll') or target_table).strip()
        target_field = (targets[0].get('cols_attrs') or target_field).strip()

    source_sql = _sql_name(source_table)
    target_sql = _sql_name(target_table)
    source_expr = _sql_value_expr(source_field)
    target_sql_field = _sql_name(target_field)
    kind = _script_kind(test_case.get('testcase_no', ''))

    if kind == "count":
        if step_index == 0:
            return f"source_count = spark.sql(\"SELECT COUNT(*) AS count FROM {source_sql}\").collect()[0]['count']"
        if step_index == 1:
            return f"target_count = spark.sql(\"SELECT COUNT(*) AS count FROM {target_sql}\").collect()[0]['count']"
        return "assert source_count == target_count, f\"Count mismatch: source={source_count}, target={target_count}\""

    if kind == "null":
        return (
            f"null_count = spark.sql(\"SELECT COUNT(*) AS count FROM {target_sql} WHERE {target_sql_field} IS NULL\").collect()[0]['count']\n"
            f"assert null_count == 0, f\"Found {{null_count}} NULL values in {target_field}\""
        )

    if kind == "duplicate":
        return (
            f"duplicate_count = spark.sql(\"SELECT {target_sql_field} FROM {target_sql} GROUP BY {target_sql_field} HAVING COUNT(*) > 1\").count()\n"
            f"assert duplicate_count == 0, f\"Found {{duplicate_count}} duplicate {target_field} values in {target_table}\""
        )

    if kind == "audit":
        return (
            f"target_df = spark.table('{target_table.replace(chr(39), '')}')\n"
            "audit_columns = [column for column in target_df.columns if any(token in column.lower() for token in ('audit', 'load_date', 'created_date', 'updated_date', 'insert_ts', 'update_ts'))]\n"
            f"assert audit_columns, 'No audit columns found on {target_table}'\n"
            "null_audit = target_df.filter(' OR '.join(f'{column} IS NULL' for column in audit_columns))\n"
            "assert null_audit.count() == 0, f'Null audit values in {audit_columns}'"
        )

    if step_index == 0:
        return f"expected = spark.sql(\"SELECT {source_expr} AS {target_sql_field} FROM {source_sql}\")"
    if step_index == 1:
        return f"actual = spark.sql(\"SELECT {target_sql_field} FROM {target_sql}\")"
    return (
        "assert [row[0] for row in expected.orderBy(expected.columns[0]).collect()] == "
        "[row[0] for row in actual.orderBy(actual.columns[0]).collect()], "
        f"\"Values loaded into {target_field} do not match {source_field}\""
    )

