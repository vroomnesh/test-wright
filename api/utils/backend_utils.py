def etl_llm_answer(
    *,
    sources: list[dict],
    targets: list[dict],
    etl_test_type: str,
    rules: str,
    language: str,
    oa: OpenAI,
    user_role: str = "user",
) -> str:
    """
    Build a single prompt from all ETL form inputs,
    """

    # Format sources & targets
    def fmt_entries(side: list[dict], label: str) -> str:
        lines = []
        for i, s in enumerate(side, start=1):
            entry = f"{i}. {s['type']} -> {s['db']}.{s['coll']}"
            if s.get("cols_attrs"):
                entry += f"\n   • columns & attrs: {s['cols_attrs']}"
            lines.append(entry)
        return "\n".join(lines)

    src_block = fmt_entries(sources, "sources")
    tgt_block = fmt_entries(targets, "targets")

    # Split & number rules
    rule_lines = [r.strip() for r in rules.splitlines() if r.strip()]
    rules_block = "\n".join(f"{i+1}. {r}" for i, r in enumerate(rule_lines))

    # Assemble user prompt
    user_prompt = f"""
You are a QA engineer. Generate a **{etl_test_type}** ETL test script in **{language}**.

Use these data **sources**, including their columns & attributes:
{src_block}

Use these **targets**, including their columns & attributes:
{tgt_block}

Apply the following **transformation rules** exactly (one test per rule):
{rules_block}

IMPORTANT REQUIREMENTS:
1. **Use ACTUAL field names** from the sources and targets - do NOT use generic names like "col1", "col2"
2. **Extract specific field names** from the cols_attrs sections and use them in your test data
3. **Create realistic test data** that matches the actual field types and names
4. **Generate separate test functions** for each transformation rule
5. **Use meaningful test data** that demonstrates the transformation logic

Write one test function per transformation rule in {language}.
When the language is Python or PySpark, use pytest, a SparkSession fixture, and DataFrame fixtures whose columns are the real source and target fields.
The expected fixture must contain only the target columns being checked, under the target column names.

{ETL_TEST_SCRIPT_RULES}
"""

    # Call chat API
    system_msg = {
        "role": "system",
        "content": "You are a QA engineer. Produce runnable ETL tests that assert the requested rule. Never generate a load job."
    }
    user_msg = {"role": user_role, "content": user_prompt}

    env        = load_env()
    chat_model = env["CHAT_MODEL"]
    if not chat_model:
        raise RuntimeError("CHAT_MODEL not set in .env")

    resp = oa.chat.completions.create(
        model=chat_model,
        messages=[system_msg, user_msg],
        max_tokens=8192,
        temperature=0.2,
    )
    script = resp.choices[0].message.content.strip()
    if script.startswith("```"):
        lines = script.splitlines()
        lines = lines[1:]
        if lines and lines[-1].strip().startswith("```"):
            lines = lines[:-1]
        script = "\n".join(lines).strip()
    return _strip_trailing_prose(script)


def _strip_trailing_prose(script: str) -> str:
    """Drop an explanation the model appends after the test code."""
    code_prefixes = (
        "import ", "from ", "def ", "class ", "@", "assert ", "return ",
        "if ", "elif ", "else:", "for ", "while ", "with ", "try:", "except",
        "finally:", "#",
    )
    last_code = -1
    for index, line in enumerate(script.splitlines()):
        stripped = line.strip()
        if not stripped:
            continue
        if (
            line.startswith((" ", "\t"))
            or stripped.startswith(code_prefixes)
            or stripped.endswith((":", ",", "\\", "(", "[", "{"))
            or stripped in {")", "]", "}"}
            or "=" in stripped
        ):
            last_code = index
    if last_code < 0:
        return script
    return "\n".join(script.splitlines()[:last_code + 1]).strip()

