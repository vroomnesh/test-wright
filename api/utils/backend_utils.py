# Initialize the OpenAI and Weaviate clients
def init_openai(env: dict) -> OpenAI:
    """Initialize the OpenAI client. Does not connect to Weaviate."""
    api_key = env.get("OPENAI_API_KEY")
    if not api_key:
        raise RuntimeError(
            "OPENAI_API_KEY is not set. Add your OpenAI API key to the .env file."
        )
    return OpenAI(api_key=api_key)


def init_clients(env):
    """Initialize OpenAI and Weaviate clients"""
    oa = init_openai(env)

    # Fix Weaviate URL format (ensure https://)
    weaviate_url = env["WEAVIATE_URL"]
    if not weaviate_url.startswith("https://"):
        weaviate_url = f"https://{weaviate_url}"

    # Header is used by Weaviate's OpenAI modules. Embeddings in this app are
    # generated by the OpenAI client above and stored with vectorizer=none.
    client = weaviate.connect_to_wcs(
        cluster_url      = weaviate_url,
        auth_credentials = Auth.api_key(env["WEAVIATE_API_KEY"]),
        headers          = {"X-OpenAI-Api-Key": env["OPENAI_API_KEY"]},
    )
    atexit.register(client.close)  # Ensure cleanup on exit
    return oa, client


@contextmanager
def weaviate_session(env=None):
    """Context manager for Weaviate and OpenAI client sessions"""
    if env is None:
        env = load_env()
    oa, client = init_clients(env)
    try:
        yield oa, client
    finally:
        client.close()


def ensure_chunk_schema(client, class_name: str = "Business"):
    """Ensure Weaviate schema exists for document chunks"""
    if not client.collections.exists(class_name):
        props = [
            Property(name="chunk_text",  data_type=DataType.TEXT),
            Property(name="doc_id",      data_type=DataType.TEXT),
            Property(name="chunk_index", data_type=DataType.INT),
            Property(name="user_id",     data_type=DataType.TEXT),
        ]
        # This Weaviate Cloud cluster only allows the hfresh vector index.
        client.collections.create(
            name               = class_name,
            vectorizer_config  = Configure.Vectorizer.none(),
            vector_index_config = Configure.VectorIndex.hfresh(),
            properties         = props
        )


def embed_chunks(oa, chunks, model_name):
    resp = oa.embeddings.create(model=model_name, input=chunks)
    return [item.embedding for item in resp.data]


def index_into_weaviate(client, oa, chunks, doc_id, user_id, class_name: str = "Business"):
    ensure_chunk_schema(client, class_name)
    env     = load_env()
    vectors = embed_chunks(oa, chunks, env["EMB_MODEL"])
    collection = client.collections.get(class_name)

    with collection.batch.fixed_size(batch_size=50) as batch:
        for idx, (chunk, vec) in enumerate(zip(chunks, vectors)):
            batch.add_object(
                properties = {
                    "chunk_text":  chunk,
                    "doc_id":      doc_id,
                    "chunk_index": idx,
                    "user_id":     user_id
                },
                vector = vec
            )


def semantic_search(query: str, oa, client, user_id: str, class_name: str = "Business", k: int = 5, fetch_multiplier: int = 5):
    # Embed the query
    env       = load_env()
    emb_model = env["EMB_MODEL"]
    resp      = oa.embeddings.create(model=emb_model, input=[query])
    qvec      = resp.data[0].embedding

    builder = client.collections.get(class_name).query
    result = builder.near_vector(
        qvec,
        limit=k * fetch_multiplier,
        return_properties=["chunk_text", "chunk_index", "user_id"]
    )
    objs = result.objects  # a list of DataObject

    filtered_texts = [
        o.properties["chunk_text"]
        for o in objs
        if o.properties.get("user_id") == user_id
    ]

    return filtered_texts[:k]


